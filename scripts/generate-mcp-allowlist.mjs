// Generates the static allowlist of documented REMOTE MCP endpoints that power the product
// pages' "Try it → live MCP handshake" (components/TryIt/*) and the worker's /api/mcp-probe
// (infra/cloudflare-proxy/worker.js).
//
// Sources scanned — all committed data, never the network:
//   data/<arena>/products.json      links.mcp
//   data/<arena>/evidence/*.json    every https:// URL in the raw JSON
//   data/<arena>/proofs/**/*.txt    every https:// URL in recorded transcripts
//
// A URL only qualifies as a live endpoint when BOTH hold:
//   1. its hostname starts with "mcp." and its path is exactly "/", "/mcp", or "/sse"
//      (docs pages like docs.stripe.com/mcp are documentation, not servers), and
//   2. its registrable domain matches one of the product's own documented domains
//      (urls.* / links.*) — so a transcript for product X that happens to mention another
//      vendor's MCP server never allowlists that server under X.
//
// Output: lib/mcpEndpoints.ts (imported by the site) — and the SAME map must be pasted into
// worker.js's MCP_ENDPOINTS (the worker is dependency-free by design). A unit test
// (infra/cloudflare-proxy/__tests__/mcp-probe.test.ts) asserts the two stay in sync.
//
// NEVER accept arbitrary URLs at probe time: this build-time scan is the only door in.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const DATA = path.join(ROOT, 'data')

const URL_RE = /https:\/\/[a-zA-Z0-9.-]+(?:\/[^\s"'`)\]<>,]*)?/g

// Naive registrable domain: last two labels. Fine for the vendor domains in this corpus
// (no public-suffix two-level TLDs like .co.uk appear in any product URL today).
function regDomain(hostname) {
  return hostname.toLowerCase().split('.').slice(-2).join('.')
}

// Endpoint candidate: host mcp.*, path exactly one of "/", "/mcp", "/sse".
const PATH_RANK = { '/mcp': 0, '/sse': 1, '/': 2 } // prefer the specific transport path
function asEndpoint(raw) {
  let url
  try {
    url = new URL(raw)
  } catch {
    return null
  }
  if (url.protocol !== 'https:' || url.port || url.username || url.password) return null
  const host = url.hostname.toLowerCase()
  if (!host.startsWith('mcp.')) return null
  // Trailing sentence punctuation swept up by the URL regex ("…/mcp. This endpoint…").
  const pathName = url.pathname.replace(/[.,;:]+$/, '').replace(/\/+$/, '') || '/'
  if (!(pathName in PATH_RANK)) return null
  return { url: `https://${host}${pathName === '/' ? '/' : pathName}`, host, rank: PATH_RANK[pathName] }
}

function urlsIn(text) {
  return text.match(URL_RE) ?? []
}

function productDomains(product) {
  const all = [
    ...Object.values(product.urls ?? {}).flat(),
    ...Object.values(product.links ?? {}),
  ].filter((u) => typeof u === 'string')
  const domains = new Set()
  for (const u of all) {
    try {
      domains.add(regDomain(new URL(u).hostname))
    } catch { /* skip malformed */ }
  }
  return domains
}

const endpoints = new Map() // "arena/product" -> { url, rank }

function consider(key, domains, rawUrl) {
  const ep = asEndpoint(rawUrl)
  if (!ep) return
  if (!domains.has(regDomain(ep.host))) return // vendor-domain guard
  const existing = endpoints.get(key)
  if (!existing || ep.rank < existing.rank) endpoints.set(key, ep)
}

for (const arena of fs.readdirSync(DATA, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name)) {
  const productsFile = path.join(DATA, arena, 'products.json')
  if (!fs.existsSync(productsFile)) continue
  const products = JSON.parse(fs.readFileSync(productsFile, 'utf8'))
  for (const product of products) {
    const key = `${arena}/${product.id}`
    const domains = productDomains(product)
    if (product.links?.mcp) consider(key, domains, product.links.mcp)

    const evidenceFile = path.join(DATA, arena, 'evidence', `${product.id}.json`)
    if (fs.existsSync(evidenceFile)) {
      for (const u of urlsIn(fs.readFileSync(evidenceFile, 'utf8'))) consider(key, domains, u)
    }

    const proofsDir = path.join(DATA, arena, 'proofs', product.id)
    if (fs.existsSync(proofsDir)) {
      for (const f of fs.readdirSync(proofsDir).filter((f) => f.endsWith('.txt'))) {
        for (const u of urlsIn(fs.readFileSync(path.join(proofsDir, f), 'utf8'))) consider(key, domains, u)
      }
    }
  }
}

const sorted = [...endpoints.entries()].sort(([a], [b]) => a.localeCompare(b))
const entries = sorted.map(([key, ep]) => `  '${key}': '${ep.url}',`).join('\n')

const ts = `// GENERATED by scripts/generate-mcp-allowlist.mjs — do not edit by hand; re-run the script
// after data changes. Maps "arena/productId" to that product's OWN documented remote MCP
// endpoint (scanned from committed data with a vendor-domain guard — see the script header).
// The identical map is hardcoded as MCP_ENDPOINTS in infra/cloudflare-proxy/worker.js (kept
// dependency-free on purpose); a unit test asserts the two never drift.
export const MCP_ENDPOINTS: Record<string, string> = {
${entries}
}

export function mcpEndpointFor(category: string, productId: string): string | null {
  return MCP_ENDPOINTS[\`\${category}/\${productId}\`] ?? null
}
`

fs.writeFileSync(path.join(ROOT, 'lib', 'mcpEndpoints.ts'), ts)
console.log(`generate-mcp-allowlist: ${sorted.length} endpoints -> lib/mcpEndpoints.ts`)
console.log('\nPaste into worker.js MCP_ENDPOINTS:\n')
console.log(`const MCP_ENDPOINTS = {\n${entries}\n}`)
