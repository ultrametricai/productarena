// Generates the static demo-call map that powers the product pages' "Try it → run a real
// call" (components/TryIt/*) and the worker's /api/mcp-probe `action: 'call'`
// (infra/cloudflare-proxy/worker.js).
//
// Source: data/mcp-demo-calls.json — a HAND-CURATED list. Every entry is one read-only,
// no-side-effect tool call with canned safe arguments that was verified LIVE against the
// vendor's endpoint before being committed (curation rule: if the call needs auth, writes
// anything, or spends anything, it does not belong here). Keys are "arena/productId" and must
// exist in the MCP_ENDPOINTS allowlist (lib/mcpEndpoints.ts), with one exception:
// "self/productarena" — our own /productarena/mcp endpoint, which the worker dispatches
// in-process (a worker fetch()ing its own route would hit the origin instead of the handler).
//
// Output: lib/mcpDemoCalls.ts (imported by the site) — and the SAME map must be pasted into
// worker.js's MCP_DEMO_CALLS (the worker is dependency-free by design). A unit test
// (infra/cloudflare-proxy/__tests__/mcp-demo-call.test.ts) asserts the two stay in sync.
//
// NEVER accept tool names or arguments at request time: this build-time list is the only
// door in — the worker ignores anything call-shaped a client sends.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const SELF_KEY = 'self/productarena'

const demoCalls = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'mcp-demo-calls.json'), 'utf8'))

// Validate against the generated allowlist (regex-parsed — lib/mcpEndpoints.ts is generated
// TS, and this script stays dependency-free like its sibling generate-mcp-allowlist.mjs).
const endpointsSrc = fs.readFileSync(path.join(ROOT, 'lib', 'mcpEndpoints.ts'), 'utf8')
const allowlisted = new Set([...endpointsSrc.matchAll(/'([a-z0-9-]+\/[a-z0-9-]+)':/g)].map((m) => m[1]))

for (const [key, entry] of Object.entries(demoCalls)) {
  if (!/^[a-z0-9-]+\/[a-z0-9-]+$/.test(key)) throw new Error(`bad key shape: ${key}`)
  if (key !== SELF_KEY && !allowlisted.has(key)) {
    throw new Error(`${key} is not in the MCP_ENDPOINTS allowlist (lib/mcpEndpoints.ts)`)
  }
  if (typeof entry.tool !== 'string' || !entry.tool.trim()) throw new Error(`${key}: "tool" required`)
  if (typeof entry.label !== 'string' || !entry.label.trim()) throw new Error(`${key}: "label" required`)
  if (!entry.args || typeof entry.args !== 'object' || Array.isArray(entry.args)) {
    throw new Error(`${key}: "args" must be an object (use {} for none)`)
  }
}

const sorted = Object.keys(demoCalls).sort()
const entries = sorted
  .map((key) => {
    const { tool, args, label } = demoCalls[key]
    return `  '${key}': { tool: ${JSON.stringify(tool)}, args: ${JSON.stringify(args)}, label: ${JSON.stringify(label)} },`
  })
  .join('\n')

const ts = `// GENERATED by scripts/generate-mcp-demo-calls.mjs — do not edit by hand; edit
// data/mcp-demo-calls.json (hand-curated, live-verified read-only tool calls) and re-run the
// script. The identical map is hardcoded as MCP_DEMO_CALLS in infra/cloudflare-proxy/worker.js
// (kept dependency-free on purpose); a unit test asserts the two never drift.
export interface McpDemoCall {
  /** Tool to call — a read-only, no-side-effect tool verified live before curation. */
  tool: string
  /** Canned safe arguments — the worker never accepts arguments from clients. */
  args: Record<string, unknown>
  /** Human label for the "run a real call" button. */
  label: string
}

export const MCP_DEMO_CALLS: Record<string, McpDemoCall> = {
${entries}
}

export function mcpDemoCallFor(category: string, productId: string): McpDemoCall | null {
  return MCP_DEMO_CALLS[\`\${category}/\${productId}\`] ?? null
}
`

fs.writeFileSync(path.join(ROOT, 'lib', 'mcpDemoCalls.ts'), ts)
console.log(`generate-mcp-demo-calls: ${sorted.length} demo calls -> lib/mcpDemoCalls.ts`)
console.log('\nPaste into worker.js MCP_DEMO_CALLS:\n')
console.log(`const MCP_DEMO_CALLS = {\n${entries}\n}`)
